-- Which categories contribute the most to overall sales?
SELECT
	category,
	total_sales,
	SUM(total_sales) OVER() overall_sales,
	CONCAT(ROUND(CAST(total_sales AS float)/SUM(total_sales) OVER() * 100, 2), '%')  percent_sales
FROM(
SELECT
	p.category,
	SUM(f.sales_amount) total_sales
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY category
)t
ORDER BY percent_sales DESC
	
-- ==========================
-- Data Segmentation
-- ==========================
	
/* Segment products into cost ranges and
count how many products fall into each segment
*/
WITH cte_products_segmentation AS(
SELECT
	product_key,
	product_name,
	cost,
	CASE
		WHEN cost < 100 THEN 'Below 100'
		WHEN cost <= 500 THEN '100-500'
		WHEN cost <= 1000 THEN '500-1000'
		ELSE 'Above 1000'
	END AS cost_range
FROM gold.dim_products
)
SELECT 
	cost_range,
	COUNT(product_key) AS total_products
FROM cte_products_segmentation
GROUP BY cost_range
ORDER BY total_products DESC

/* Group customers into three segments based on their spending behaviour.
- VIP: at least 12 months of history and spending more than 5,000 Euros
- Regular: at least 12 months of history but spending 5,000 Euros or less
- NEW: lifespan less than 12 months
-- Also find the total number of customers by each group
*/
WITH cte_customer_spending AS(
SELECT 
	c.customer_key,
	SUM(f.sales_amount) total_money_spent,
	MIN(f.order_date) AS first_order,
	MAX(f.order_date) AS last_order,
	DATEDIFF(MONTH, MIN(f.order_date), MAX(f.order_date)) AS lifespan
FROM gold.fact_sales f
LEFT JOIN
gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY c.customer_key
)
SELECT 
	customer_segment,
	COUNT(customer_key) AS total_customers
FROM(
SELECT
	customer_key,
	total_money_spent,
	lifespan,
	CASE 
		WHEN total_money_spent > 5000 AND lifespan >= 12 THEN 'VIP'
		WHEN total_money_spent <= 5000 AND lifespan >= 12 THEN 'Regular'
		ELSE 'New'
	END customer_segment
FROM cte_customer_spending)t
GROUP BY customer_segment
ORDER BY total_customers DESC





-- ==========================
-- Cummulative Aggregation
-- ==========================

-- Calcualate the total sales per month
-- and the running total of sales over time

SELECT
	order_date,
	total_sales,
	SUM(total_sales) OVER(ORDER BY order_date) running_total_sales,
	AVG(avg_sales) OVER(ORDER BY order_date) moving_average_price
FROM(
SELECT 
	DATETRUNC(YEAR,order_date) AS order_date,
	SUM(sales_amount) total_sales,
	AVG(sales_amount) avg_sales
FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY DATETRUNC(YEAR,order_date)
)t

-- ==========================
-- Performance Analysis
-- ==========================

-- Analyze the yearly performance of products 
-- by comparing each product's sales to both
-- its average sales performance and the previous year's sales
IF OBJECT_ID('cte_yearly_product_sales', 'V') IS NOT NULL
DROP VIEW cte_yearly_product_sales
GO
CREATE VIEW gold.yearly_product_sales AS
WITH cte_yearly_product_sales AS(
SELECT
	YEAR(s.order_date) order_year,
	p.product_name,
	SUM(s.sales_amount) current_sales
FROM gold.fact_sales s
LEFT JOIN gold.dim_products p
ON p.product_key = s.product_key
WHERE YEAR(s.order_date) IS NOT NULL
GROUP BY 
	YEAR(s.order_date),
	p.product_name
)
SELECT 
	order_year,
	product_name,
	current_sales,
	AVG(current_sales) OVER(PARTITION BY product_name) avg_sales,
	current_sales - AVG(current_sales) OVER(PARTITION BY product_name) diff_avg,
	CASE 
		WHEN current_sales - AVG(current_sales) OVER(PARTITION BY product_name) > 0 THEN 'Above average'
		WHEN current_sales - AVG(current_sales) OVER(PARTITION BY product_name) < 0 THEN 'Below average'
		ELSE 'Average'
	END AS avg_change,
	LAG(current_sales) OVER(PARTITION BY product_name ORDER BY order_year) AS py_sales,
	current_sales - LAG(current_sales) OVER(PARTITION BY product_name ORDER BY order_year) AS diff_py,
	CASE 
		WHEN current_sales - LAG(current_sales) OVER(PARTITION BY product_name ORDER BY order_year) > 0 THEN 'Increase'
		WHEN current_sales - LAG(current_sales) OVER(PARTITION BY product_name ORDER BY order_year) < 0 THEN 'Decrease'
		ELSE 'No change'
	END AS py_change
FROM cte_yearly_product_sales

